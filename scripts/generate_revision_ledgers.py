#!/usr/bin/env python3
"""
Generate comprehensive multi-seed experimental accounting ledgers and statistical summary tables for manuscript revision.

Definitions:
- Rejected Proposals (rejected_count): Candidate bounding-box proposals generated by the model during active pool acquisition that failed verification thresholds (confidence below tau_conf or IoU below 0.5 with ground truth).
- Undetected Objects (undetected_count): Ground-truth threat objects present in acquired pool images that were missed by model candidate proposals.
"""

import os
import json
import csv
import glob
import numpy as np

def main():
    base_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out_dir = os.path.join(base_dir, 'outputs')
    ledger_dir = os.path.join(out_dir, 'revision_ledgers')
    os.makedirs(ledger_dir, exist_ok=True)

    archs = ['yolov8n', 'yolo11n', 'yolo12n']
    inits = ['pretrained', 'random']
    budgets = ['10ep', '100ep']
    seeds = [42, 123, 456, 789, 1011]

    detailed_rows = []
    table5_data = {}

    for a in archs:
        for i in inits:
            for b in budgets:
                b_str = '' if b == '10ep' else '_100ep'
                cond_key = (a, i, b)
                table5_data[cond_key] = {
                    'r1_val_map': [],
                    'r5_val_map': [],
                    'test_map': []
                }

                for s in seeds:
                    folder_name = f'{a}_{i}{b_str}_seed_{s}'
                    p = os.path.join(out_dir, folder_name)
                    if not os.path.isdir(p) and s == 42:
                        p = os.path.join(out_dir, f'{a}_{i}{b_str}')

                    test_map50 = None
                    test_prec = None
                    test_rec = None
                    ft_path = os.path.join(p, 'final_test_metrics.json')
                    if os.path.exists(ft_path):
                        with open(ft_path, 'r', encoding='utf-8') as f:
                            ft = json.load(f)
                        test_map50 = ft['metrics'].get('mAP50', None)
                        test_prec = ft['metrics'].get('precision', None)
                        test_rec = ft['metrics'].get('recall', None)

                    for r in range(1, 6):
                        m_path = os.path.join(p, f'round_{r}_metrics.json')
                        if not os.path.exists(m_path):
                            continue
                        with open(m_path, 'r', encoding='utf-8') as f:
                            m = json.load(f)

                        cd = m.get('class_distribution', {})
                        met = m.get('metrics', {})

                        row = {
                            'architecture': a,
                            'initialisation': i,
                            'budget_epochs': 10 if b == '10ep' else 100,
                            'seed': s,
                            'round': r,
                            'training_set_size': m.get('training_set_size', 0),
                            'verified_samples_added': m.get('verified_samples_added', 0),
                            'rejected_count': m.get('rejected_count', 0),
                            'undetected_count': m.get('undetected_count', 0),
                            'knife_boxes': cd.get('knife_boxes', 0),
                            'pistol_boxes': cd.get('pistol_boxes', 0),
                            'total_boxes': cd.get('total_boxes', 0),
                            'images_with_knife': cd.get('images_with_knife', 0),
                            'images_with_pistol': cd.get('images_with_pistol', 0),
                            'total_images': cd.get('total_images', 0),
                            'actual_stopped_epoch': m.get('actual_stopped_epoch', 0),
                            'optimizer_steps': m.get('optimizer_steps', 0),
                            'cumulative_optimizer_steps': m.get('cumulative_optimizer_steps', 0),
                            'images_processed': m.get('images_processed', 0),
                            'cumulative_images_processed': m.get('cumulative_images_processed', 0),
                            'gflops': m.get('gflops', 0.0),
                            'training_tflops': m.get('training_tflops', 0.0),
                            'cumulative_training_tflops': m.get('cumulative_training_tflops', 0.0),
                            'val_mAP50': met.get('mAP50', 0.0),
                            'val_precision': met.get('precision', 0.0),
                            'val_recall': met.get('recall', 0.0),
                            'final_held_out_test_mAP50': test_map50 if r == 5 else None
                        }
                        detailed_rows.append(row)

                        if r == 1:
                            table5_data[cond_key]['r1_val_map'].append(met.get('mAP50', 0.0))
                        elif r == 5:
                            table5_data[cond_key]['r5_val_map'].append(met.get('mAP50', 0.0))
                            if test_map50 is not None:
                                table5_data[cond_key]['test_map'].append(test_map50)

    fieldnames = list(detailed_rows[0].keys())
    with open(os.path.join(ledger_dir, 'multi_seed_detailed_accounting.csv'), 'w', newline='', encoding='utf-8') as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(detailed_rows)

    t_val = 2.776
    stat_rows = []
    for (a, i, b), data in table5_data.items():
        r1_m, r1_sd = float(np.mean(data['r1_val_map'])), float(np.std(data['r1_val_map'], ddof=1))
        r1_ci = t_val * (r1_sd / np.sqrt(5))
        r5_m, r5_sd = float(np.mean(data['r5_val_map'])), float(np.std(data['r5_val_map'], ddof=1))
        r5_ci = t_val * (r5_sd / np.sqrt(5))
        t_m, t_sd = float(np.mean(data['test_map'])), float(np.std(data['test_map'], ddof=1))
        t_ci = t_val * (t_sd / np.sqrt(5))
        stat_rows.append({
            'architecture': a,
            'initialisation': i,
            'budget_epochs': 10 if b == '10ep' else 100,
            'r1_val_mAP_mean': r1_m,
            'r1_val_mAP_sd': r1_sd,
            'r1_val_mAP_ci95': r1_ci,
            'r5_val_mAP_mean': r5_m,
            'r5_val_mAP_sd': r5_sd,
            'r5_val_mAP_ci95': r5_ci,
            'held_out_test_mAP_mean': t_m,
            'held_out_test_mAP_sd': t_sd,
            'held_out_test_mAP_ci95': t_ci
        })

    with open(os.path.join(ledger_dir, 'table_5_statistical_summary.csv'), 'w', newline='', encoding='utf-8') as f:
        writer = csv.DictWriter(f, fieldnames=list(stat_rows[0].keys()))
        writer.writeheader()
        writer.writerows(stat_rows)

    print('Successfully created ledgers and statistical summary in:', ledger_dir)

if __name__ == '__main__':
    main()
